@dashboard_bp.route("/result/<int:pred_id>")
@login_required
def result(pred_id: int):
    pred = db.session.get(Prediction, pred_id)
    if not pred or pred.user_id != current_user.id:
        flash("Result not found.", "error")
        return redirect(url_for("dashboard.detect"))

    health  = pred.health_score()
    similar = Prediction.similar_cases(
        user_id=current_user.id, predicted_class=pred.predicted_class,
        exclude_id=pred.id, confidence=pred.confidence, limit=5)

    # Build top-3 from stored probabilities
    probs_dict = pred.probs_dict()
    top3 = sorted(
        [{"class_name": k, "probability": v, "rank": 0}
         for k, v in probs_dict.items()],
        key=lambda x: -x["probability"]
    )[:3]
    for i, t in enumerate(top3): t["rank"] = i + 1

    # Uncertainty based on stored confidence
    from webapp.app.ml.predictor import _uncertainty_flag
    uncertainty = _uncertainty_flag(pred.confidence, pred.predicted_class)

    return render_template(
        "dashboard/result.html",
        pred        = pred,
        class_info  = current_app.config["CLASS_INFO"],
        health      = health,
        similar     = similar,
        top3        = top3,
        uncertainty = uncertainty,
    )


