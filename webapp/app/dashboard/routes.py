def _allowed_file(filename: str) -> bool:
    ext = filename.rsplit(".", 1)[-1].lower() if "." in filename else ""
    return ext in current_app.config["ALLOWED_EXTENSIONS"]


def _parse_filters():
    return {
        "cls_filter":   request.args.get("cls", ""),
        "date_from":    request.args.get("date_from", ""),
        "date_to":      request.args.get("date_to", ""),
        "conf_min":     _safe_float(request.args.get("conf_min", "0"), 0.0),
        "conf_max":     _safe_float(request.args.get("conf_max", "100"), 100.0) / 100.0,
        "model_filter": request.args.get("model", ""),
        "search":       request.args.get("q", ""),
    }


def _safe_float(val, default=0.0) -> float:
    try:    return float(val)
    except: return default


def _build_csv_response(preds: list, filename: str = "leafiq_export.csv") -> Response:
    def generate():
        buf = io.StringIO()
        w   = csv.writer(buf)
        w.writerow(["ID","Original Filename","Predicted Class","Confidence %",
                    "Model","Grad-CAM","Inference ms","Date"])
        yield buf.getvalue(); buf.seek(0); buf.truncate()
        for p in preds:
            w.writerow([p.id, p.original_name, p.predicted_class,
                        f"{p.confidence*100:.2f}", p.model_used,
                        "Yes" if p.gradcam_file else "No",
                        f"{p.inference_ms:.1f}" if p.inference_ms else "",
                        p.created_at.strftime("%Y-%m-%d %H:%M")])
            yield buf.getvalue(); buf.seek(0); buf.truncate()
    return Response(generate(), mimetype="text/csv",
                    headers={"Content-Disposition": f'attachment; filename="{filename}"'})


def _build_pdf_response(preds, title, stats=None, filename="leafiq.pdf") -> Response:
    try:
        from fpdf import FPDF
    except ImportError:
        flash("PDF library not installed. Returning CSV.", "info")
        return _build_csv_response(preds, filename.replace(".pdf", ".csv"))

    def safe(t): return str(t).encode("latin-1", errors="replace").decode("latin-1")

    pdf = FPDF(); pdf.set_auto_page_break(auto=True, margin=15); pdf.add_page()
    pdf.set_font("Helvetica","B",16); pdf.cell(0,10,safe("LeafIQ - Plant Disease Detection"),ln=True)
    pdf.set_font("Helvetica","B",13); pdf.cell(0,8,safe(title),ln=True)
    pdf.set_font("Helvetica","",9)
    pdf.cell(0,6,safe(f"Generated: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}  Records: {len(preds)}"),ln=True)
    pdf.ln(4)
    if stats:
        pdf.set_font("Helvetica","B",10); pdf.cell(0,6,"Summary Statistics",ln=True)
        pdf.set_font("Helvetica","",9)
        for k,v in stats.items(): pdf.cell(0,5,safe(f"  {k}: {v}"),ln=True)
        pdf.ln(3)
    col_w=[12,62,38,22,26,15,25]
    hdrs=["ID","Filename","Class","Conf%","Model","GradCAM","Date"]
    pdf.set_font("Helvetica","B",8); pdf.set_fill_color(30,70,30); pdf.set_text_color(255,255,255)
    for w,h in zip(col_w,hdrs): pdf.cell(w,6,h,border=1,fill=True)
    pdf.ln(); pdf.set_text_color(0,0,0); pdf.set_font("Helvetica","",8)
    for i,p in enumerate(preds):
        fill=(i%2==0)
        pdf.set_fill_color(240,248,240) if fill else pdf.set_fill_color(255,255,255)
        vals=[str(p.id), safe(p.original_name[:28]+("..."if len(p.original_name)>28 else "")),
              safe(p.predicted_class.replace("Tomato_","")), f"{p.confidence*100:.1f}",
              safe(p.model_used.replace("_"," ")), "Yes" if p.gradcam_file else "No",
              p.created_at.strftime("%Y-%m-%d")]
        for w,v in zip(col_w,vals): pdf.cell(w,5,v,border=1,fill=fill)
        pdf.ln()
    pdf.ln(4); pdf.set_font("Helvetica","I",7)
    pdf.multi_cell(0,4,safe("LeafIQ predictions are generated by a machine-learning model. "
                             "They are not agronomic diagnoses."))
    pdf_bytes = pdf.output()
    return Response(bytes(pdf_bytes) if not isinstance(pdf_bytes,bytes) else pdf_bytes,
                    mimetype="application/pdf",
                    headers={"Content-Disposition":f'attachment; filename="{filename}"'})


def _filter_summary(f):
    parts=[]
    if f.get("cls_filter"): parts.append(f"class={f['cls_filter'].replace('Tomato_','')}")
    if f.get("date_from"):  parts.append(f"from={f['date_from']}")
    if f.get("date_to"):    parts.append(f"to={f['date_to']}")
    if f.get("conf_min",0)>0: parts.append(f"conf_min={int(f['conf_min']*100)}%")
    if f.get("conf_max",1.0)<1.0: parts.append(f"conf_max={int(f['conf_max']*100)}%")
    if f.get("model_filter"): parts.append(f"model={f['model_filter']}")
    if f.get("search"): parts.append(f"search={f['search']}")
    return ", ".join(parts) if parts else "none"


