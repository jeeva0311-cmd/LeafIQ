# ── Monitoring (Phase 8) ──────────────────────────────────────────────────

@dashboard_bp.route("/monitor")
@login_required
def monitor():
    all_preds = current_user.predictions.order_by(Prediction.created_at.desc()).all()
    total     = len(all_preds)

    # Inference time stats (last 100 preds)
    recent_ms  = [p.inference_ms for p in all_preds[:100] if p.inference_ms]
    avg_ms     = round(sum(recent_ms)/len(recent_ms),1) if recent_ms else 0
    max_ms     = round(max(recent_ms),1) if recent_ms else 0
    min_ms     = round(min(recent_ms),1) if recent_ms else 0

    # Model usage split
    model_counts = {}
    for p in all_preds:
        model_counts[p.model_used] = model_counts.get(p.model_used, 0) + 1

    # Uncertain predictions (confidence < 0.60)
    uncertain = [p for p in all_preds if p.confidence < 0.60]
    uncertain_pct = round(len(uncertain)/total*100, 1) if total else 0.0

    # Daily prediction counts (last 14 days)
    daily = {}
    for p in all_preds:
        day = p.created_at.strftime("%Y-%m-%d")
        daily[day] = daily.get(day, 0) + 1
    daily_sorted = sorted(daily.items())[-14:]

    # Class-wise trend (last 50 preds)
    class_trend = {}
    for p in all_preds[:50]:
        cls = p.predicted_class
        class_trend[cls] = class_trend.get(cls, 0) + 1

    # Confidence distribution buckets
    conf_buckets = {">=90%": 0, "60-90%": 0, "40-60%": 0, "<40%": 0}
    for p in all_preds:
        c = p.confidence
        if c >= 0.90:   conf_buckets[">=90%"]  += 1
        elif c >= 0.60: conf_buckets["60-90%"] += 1
        elif c >= 0.40: conf_buckets["40-60%"] += 1
        else:           conf_buckets["<40%"]   += 1

    # Drift warning: shown only when there are >= 20 predictions
    # and the uncertain-prediction rate exceeds 30%
    drift_warning = None
    if total >= 20 and uncertain_pct > 30:
        drift_warning = (
            f"{uncertain_pct:.1f}% of recent predictions have confidence < 60%. "
            "This may indicate image quality issues, unusual leaf presentations, "
            "or a domain shift from the training data. "
            "No automatic retraining occurs — review flagged images manually."
        )

    return render_template("dashboard/monitor.html",
                           total         = total,
                           avg_ms        = avg_ms,
                           max_ms        = max_ms,
                           min_ms        = min_ms,
                           model_counts  = model_counts,
                           uncertain     = len(uncertain),
                           uncertain_pct = uncertain_pct,
                           daily         = daily_sorted,
                           class_trend   = class_trend,
                           conf_buckets  = conf_buckets,
                           drift_warning = drift_warning,
                           class_display = current_app.config["CLASS_DISPLAY"],
                           recent_preds  = all_preds[:10])


