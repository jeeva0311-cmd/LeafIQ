@dashboard_bp.route("/detect/upload", methods=["POST"])
@login_required
def upload():
    if "image" not in request.files:
        flash("No file selected.", "error"); return redirect(url_for("dashboard.detect"))
    file = request.files["image"]
    if not file or file.filename == "":
        flash("No file selected.", "error"); return redirect(url_for("dashboard.detect"))
    if not _allowed_file(file.filename):
        flash("Unsupported file type. Upload JPG, PNG, BMP or WebP.", "error")
        return redirect(url_for("dashboard.detect"))

    original_name = file.filename
    ext           = original_name.rsplit(".",1)[-1].lower()
    safe_name     = f"{uuid.uuid4().hex}.{ext}"
    upload_dir    = current_app.config["UPLOAD_FOLDER"]
    save_path     = os.path.join(upload_dir, safe_name)
    file.save(save_path)

    model_choice = request.form.get("model", "custom_cnn")
    if model_choice not in ("custom_cnn", "cnn_xgboost"):
        model_choice = "custom_cnn"

    # Per-prediction Grad-CAM toggle (Phase 8: user can skip it)
    skip_gradcam = request.form.get("skip_gradcam") == "1"

    gradcam_name = f"gradcam_{uuid.uuid4().hex}.png"
    gradcam_path = os.path.join(upload_dir, gradcam_name)

    try:
        from webapp.app.ml.predictor import predict as ml_predict
        result = ml_predict(
            image_path        = save_path,
            model_choice      = model_choice,
            cnn_ckpt          = current_app.config["CNN_CHECKPOINT"],
            xgb_pkl           = current_app.config["XGB_PKL"],
            input_hw          = current_app.config["CNN_INPUT_HW"],
            gradcam_save_path = gradcam_path,
            skip_gradcam      = skip_gradcam,
        )
    except ValueError as ve:
        os.remove(save_path)
        flash(f"Image validation failed: {ve}", "error")
        return redirect(url_for("dashboard.detect"))
    except FileNotFoundError as fe:
        os.remove(save_path)
        flash(f"Model file missing: {fe}", "error")
        return redirect(url_for("dashboard.detect"))
    except Exception as e:
        log.error("Prediction failed: %s", e, exc_info=True)
        os.remove(save_path)
        flash(f"Prediction error: {e}", "error")
        return redirect(url_for("dashboard.detect"))

    pred = Prediction(
        user_id         = current_user.id,
        filename        = safe_name,
        original_name   = original_name,
        model_used      = model_choice,
        predicted_class = result["predicted_class"],
        confidence      = result["confidence"],
        probabilities   = json.dumps(result["probabilities"]),
        inference_ms    = result.get("inference_ms"),
        gradcam_file    = gradcam_name if result.get("gradcam_generated") else None,
    )
    db.session.add(pred); db.session.commit()
    return redirect(url_for("dashboard.result", pred_id=pred.id))


